// -------------------------------------------------------------------
// Component
// -------------------------------------------------------------------

export function MobileNav(): React.JSX.Element {
  const pathname = usePathname();
  const [showMore, setShowMore] = useState(false);

  const isActive = useCallback(
    (href: string): boolean => {
      return pathname === href || pathname.startsWith(`${href}/`);
    },
    [pathname],
  );

  const toggleMore = useCallback((): void => {
    setShowMore((prev) => !prev);
  }, []);

  return (
    <>
      {/* More panel */}
      {showMore ? (
        <div className="fixed inset-x-0 bottom-16 z-40 border-t border-gray-200 bg-white shadow-lg lg:hidden">
          <nav className="grid grid-cols-3 gap-1 p-3">
            {MORE_ITEMS.map((item) => {
              const active = isActive(item.href);
              return (
                <Link
                  key={item.href}
                  href={item.href}
                  onClick={() => setShowMore(false)}
                  className={`flex min-h-[44px] flex-col items-center justify-center gap-1 rounded-lg px-2 py-2 text-xs font-medium ${
                    active
                      ? 'bg-blue-50 text-blue-700'
                      : 'text-gray-600 hover:bg-gray-50 hover:text-gray-900'
                  }`}
                >
                  {item.icon}
                  {item.label}
                </Link>
              );
            })}
          </nav>
        </div>
      ) : null}

      {/* Bottom nav bar */}
      <nav className="fixed inset-x-0 bottom-0 z-50 flex h-16 items-center justify-around border-t border-gray-200 bg-white lg:hidden">
        {MOBILE_NAV_ITEMS.map((item) => {
          const active = isActive(item.href);
          return (
            <Link
              key={item.href}
              href={item.href}
              onClick={() => setShowMore(false)}
              className={`flex min-h-[44px] min-w-[44px] flex-col items-center justify-center gap-0.5 px-2 text-xs font-medium ${
                active ? 'text-blue-700' : 'text-gray-500 hover:text-gray-700'
              }`}
            >
              {item.icon}
              <span>{item.label}</span>
            </Link>
          );
        })}

        {/* More button */}
        <button
          type="button"
          onClick={toggleMore}
          className={`flex min-h-[44px] min-w-[44px] flex-col items-center justify-center gap-0.5 px-2 text-xs font-medium ${
            showMore ? 'text-blue-700' : 'text-gray-500 hover:text-gray-700'
          }`}
          aria-label="More navigation options"
        >
          <svg
            className="h-5 w-5"
            fill="none"
            viewBox="0 0 24 24"
            stroke="currentColor"
            strokeWidth={1.5}
            aria-hidden="true"
          >
            <path
              strokeLinecap="round"
              strokeLinejoin="round"
              d="M6.75 12a.75.75 0 11-1.5 0 .75.75 0 011.5 0zM12.75 12a.75.75 0 11-1.5 0 .75.75 0 011.5 0zM18.75 12a.75.75 0 11-1.5 0 .75.75 0 011.5 0z"
            />
          </svg>
          <span>More</span>
        </button>
      </nav>
    </>
  );
}
